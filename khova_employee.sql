-- 1) Employee details
create table if not exists public.employees (
  id             bigint generated by default as identity primary key,
  name           text not null,
  phone          text,
  role           text,
  monthly_salary numeric(12,2) not null default 0 check (monthly_salary >= 0),
  join_date      date not null default current_date,
  active         boolean not null default true,
  created_at     timestamptz not null default now()
);

alter table public.employees enable row level security;
drop policy if exists "employees_all" on public.employees;
create policy "employees_all" on public.employees
  for all to authenticated using (public.is_app_user()) with check (public.is_app_user());

-- 2) Link salary payments to an employee
alter table public.expenses
  add column if not exists employee_id bigint references public.employees(id) on delete set null;

-- 3) Add Rinku (monthly salary & joining date are placeholders — edit them in the app)
insert into public.employees (name, role, monthly_salary, join_date)
select 'Rinku', 'Shop staff', 5000, '2026-09-19'
where not exists (select 1 from public.employees where name = 'Rinku');

-- 4) Attach existing salary payments to Rinku
update public.expenses
set employee_id = (select id from public.employees where name = 'Rinku' order by id limit 1)
where category = 'salary' and employee_id is null;

-- Check
select e.name, e.monthly_salary, e.join_date,
       coalesce(sum(x.amount), 0) as salary_paid
from public.employees e
left join public.expenses x on x.employee_id = e.id and x.category = 'salary'
group by e.id;
