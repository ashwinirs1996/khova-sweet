-- 1) Delete old customer-wise sales data (table is kept, rows removed)
delete from public.sales;

-- 2) Day-wise sales: one row per day, split by payment mode
create table if not exists public.daily_sales (
  id             bigint generated by default as identity primary key,
  sale_date      date not null unique,
  cash_amount    numeric(12,2) not null default 0 check (cash_amount >= 0),
  phonepe_amount numeric(12,2) not null default 0 check (phonepe_amount >= 0),
  other_amount   numeric(12,2) not null default 0 check (other_amount >= 0),
  note           text,
  created_by     uuid references auth.users(id) default auth.uid(),
  created_at     timestamptz not null default now()
);

-- 3) Expenses & payments: operating costs, khova purchases, salaries, etc.
create table if not exists public.expenses (
  id           bigint generated by default as identity primary key,
  expense_date date not null,
  category     text not null check (category in ('operating', 'purchase', 'salary', 'other')),
  payment_mode text not null check (payment_mode in ('cash', 'phonepe', 'other')),
  amount       numeric(12,2) not null check (amount > 0),
  description  text,
  created_by   uuid references auth.users(id) default auth.uid(),
  created_at   timestamptz not null default now()
);
create index if not exists expenses_date_idx on public.expenses (expense_date);

-- 4) Security: only approved staff (app_users) can read / add / edit / delete
alter table public.daily_sales enable row level security;
alter table public.expenses    enable row level security;

drop policy if exists "daily_sales_all" on public.daily_sales;
create policy "daily_sales_all" on public.daily_sales
  for all to authenticated using (public.is_app_user()) with check (public.is_app_user());

drop policy if exists "expenses_all" on public.expenses;
create policy "expenses_all" on public.expenses
  for all to authenticated using (public.is_app_user()) with check (public.is_app_user());

