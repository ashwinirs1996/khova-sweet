-- =====================================================================
-- Khova Sweet — monthly salary & deductions
-- Run in Supabase → SQL Editor AFTER khova_employee.sql. Safe to re-run.
--
-- salary_entries holds what the employee is OWED:
--   'salary'    = salary added for a month (+)
--   'deduction' = amount cut from salary, e.g. leave, advance (−)
-- Actual money PAID stays in expenses (category = 'salary').
-- =====================================================================

create table if not exists public.salary_entries (
  id          bigint generated by default as identity primary key,
  employee_id bigint not null references public.employees(id) on delete cascade,
  month       date not null check (extract(day from month) = 1),
  entry_type  text not null check (entry_type in ('salary', 'deduction')),
  amount      numeric(12,2) not null check (amount > 0),
  reason      text,
  created_by  uuid references auth.users(id) default auth.uid(),
  created_at  timestamptz not null default now()
);

-- Only one salary entry per employee per month (deductions can be many)
create unique index if not exists salary_entries_one_salary_per_month
  on public.salary_entries (employee_id, month) where entry_type = 'salary';

alter table public.salary_entries enable row level security;
drop policy if exists "salary_entries_all" on public.salary_entries;
create policy "salary_entries_all" on public.salary_entries
  for all to authenticated using (public.is_app_user()) with check (public.is_app_user());
